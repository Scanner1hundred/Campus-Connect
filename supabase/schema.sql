-- 13. PROFILE POLICIES

create policy "Users can view own profile"
on public.profiles
for select
using (auth.uid() = id);

create policy "Users can insert own profile"
on public.profiles
for insert
with check (auth.uid() = id);

create policy "Users can update own profile"
on public.profiles
for update
using (auth.uid() = id);


-- 14. MARKETPLACE LISTING POLICIES

create policy "Anyone can view available listings"
on public.marketplace_listings
for select
using (listing_status = 'Available');

create policy "Users can create their own listings"
on public.marketplace_listings
for insert
with check (auth.uid() = seller_id);

create policy "Users can update their own listings"
on public.marketplace_listings
for update
using (auth.uid() = seller_id);

create policy "Users can delete their own listings"
on public.marketplace_listings
for delete
using (auth.uid() = seller_id);

-- 15. ELECTRONIC ITEMS

create policy "Anyone can view electronic items"
on public.electronic_items
for select
using (true);

create policy "Anyone can view electronic categories"
on public.electronic_categories
for select
using (true);


-- 16. LISTING IMAGES

create policy "Anyone can view listing images"
on public.listing_images
for select
using (true);


-- 17. REVIEWS

create policy "Anyone can view reviews"
on public.reviews
for select
using (true);

create policy "Logged in users can create reviews"
on public.reviews
for insert
with check (auth.uid() = reviewer_id);
